import type { HoursReport, HoursRow } from '../api/types';
import { formatMonth } from './dates';

/**
 * PDF export of the hours report. The PDF is drawn in the browser from the rows the screen already
 * shows, which the backend has already scoped by role (a contributor's export contains only their
 * own hours): no extra endpoint, and the file always matches the table. The PDF libraries are
 * loaded on demand so they are not part of the initial bundle.
 */
export interface HoursReportPdfMeta {
  /** Who is exporting, printed in the header. */
  generatedBy: string;
  /** `YYYY-MM-DD` of the export day. */
  generatedOn: string;
  /** Human labels of filters, printed when set, e.g. `Project: ALPHA · Alpha Platform`. */
  filters?: string[];
}

export interface PdfTable {
  head: string[];
  body: string[][];
  foot: string[];
  /** Indexes of the numeric columns (right-aligned). */
  numericColumns: number[];
}

const projectLabel = (row: HoursRow): string =>
  row.projectCode ? `${row.projectCode} · ${row.projectName ?? ''}` : '';

/** The report as plain text cells, mirroring the on-screen table (columns follow `groupBy`). */
export function buildPdfTable(report: HoursReport): PdfTable {
  const dims = report.groupBy;
  const head = [
    ...(dims.includes('contributor') ? ['Contributor'] : []),
    ...(dims.includes('project') ? ['Project'] : []),
    ...(dims.includes('month') ? ['Month'] : []),
    'Total h',
    'Billable h',
    'Non-billable h',
    'Entries',
  ];
  const numbers = (r: {
    totalHours: number;
    billableHours: number;
    nonBillableHours: number;
    entryCount: number;
  }) => [r.totalHours, r.billableHours, r.nonBillableHours, r.entryCount].map(String);

  const body = report.rows.map((row) => [
    ...(dims.includes('contributor') ? [row.userName ?? ''] : []),
    ...(dims.includes('project') ? [projectLabel(row)] : []),
    ...(dims.includes('month') ? [row.month ? formatMonth(row.month) : ''] : []),
    ...numbers(row),
  ]);
  const foot = [
    ...(dims.length > 0 ? ['Total', ...Array<string>(dims.length - 1).fill('')] : []),
    ...numbers(report.totals),
  ];
  const first = head.length - 4;
  return { head, body, foot, numericColumns: [first, first + 1, first + 2, first + 3] };
}

export const hoursReportFileName = (report: HoursReport): string =>
  `hours-report_${report.from}_to_${report.to}.pdf`;

/** Builds the document (async: loads jsPDF on first use). */
export async function buildHoursReportPdf(report: HoursReport, meta: HoursReportPdfMeta) {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([
    import('jspdf'),
    import('jspdf-autotable'),
  ]);
  const doc = new jsPDF({ orientation: report.groupBy.length >= 3 ? 'landscape' : 'portrait' });
  const margin = 14;

  doc.setFontSize(16);
  doc.text('Hours report', margin, 18);
  doc.setFontSize(10);
  doc.setTextColor(90);
  const lines = [
    `Period: ${report.from} to ${report.to}`,
    `Grouped by: ${report.groupBy.join(', ')}`,
    ...(meta.filters ?? []),
    `Generated by ${meta.generatedBy} on ${meta.generatedOn}`,
  ];
  lines.forEach((line, i) => doc.text(line, margin, 25 + i * 5));
  doc.setTextColor(0);

  const table = buildPdfTable(report);
  let startY = 25 + lines.length * 5 + 3;
  if (report.truncated) {
    doc.setTextColor(170, 90, 0);
    doc.text('Showing the first 5000 rows only; narrow the range to see the rest.', margin, startY);
    doc.setTextColor(0);
    startY += 6;
  }
  autoTable(doc, {
    startY,
    margin: { left: margin, right: margin },
    head: [table.head],
    body: table.body,
    foot: [table.foot],
    showFoot: 'lastPage',
    styles: { fontSize: 9 },
    headStyles: { fillColor: [60, 60, 120] },
    footStyles: { fillColor: [235, 235, 245], textColor: 0, fontStyle: 'bold' },
    // Head, body and total cells alike: numbers line up on the right.
    didParseCell: ({ cell, column }) => {
      if (table.numericColumns.includes(column.index)) cell.styles.halign = 'right';
    },
    didDrawPage: () => {
      const { width, height } = doc.internal.pageSize;
      doc.setFontSize(8);
      doc.setTextColor(120);
      doc.text(`Page ${doc.getCurrentPageInfo().pageNumber}`, width - margin, height - 8, {
        align: 'right',
      });
      doc.setTextColor(0);
    },
  });
  return doc;
}

/** Hands a file to the browser's download mechanism (no navigation, nothing is uploaded). */
function saveBlob(blob: Blob, fileName: string): void {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = fileName;
  document.body.append(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 0);
}

/** Builds the PDF and starts the browser download. */
export async function downloadHoursReportPdf(
  report: HoursReport,
  meta: HoursReportPdfMeta,
): Promise<void> {
  const doc = await buildHoursReportPdf(report, meta);
  saveBlob(doc.output('blob'), hoursReportFileName(report));
}
