import { screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, expect, it, vi } from 'vitest';
import type { HoursReport } from '../src/api/types';
import {
  buildHoursReportPdf,
  buildPdfTable,
  hoursReportFileName,
  type HoursReportPdfMeta,
} from '../src/lib/report-pdf';
import { todayIso } from '../src/lib/dates';
import { fail, mockApi, ok, project, renderRoutes, signedInAs, users } from './helpers';

const report: HoursReport = {
  from: '2026-02-01',
  to: '2026-03-31',
  groupBy: ['contributor', 'project', 'month'],
  rows: [
    {
      userName: 'Casey Contributor',
      projectCode: 'ALPHA',
      projectName: 'Alpha Platform',
      month: '2026-03',
      totalHours: 31.75,
      billableHours: 20.5,
      nonBillableHours: 11.25,
      entryCount: 7,
    },
  ],
  totals: { totalHours: 31.75, billableHours: 20.5, nonBillableHours: 11.25, entryCount: 7 },
  truncated: false,
};
const meta = { generatedBy: 'Alex Admin', generatedOn: '2026-03-31' };
const pdfText = async (r: HoursReport, m: HoursReportPdfMeta = meta) =>
  (await buildHoursReportPdf(r, m)).output('arraybuffer');
const asText = (buffer: ArrayBuffer) => new TextDecoder('latin1').decode(buffer);

describe('PDF table', () => {
  it('mirrors the on-screen columns, following the grouping', () => {
    const table = buildPdfTable(report);

    expect(table.head).toEqual([
      'Contributor',
      'Project',
      'Month',
      'Total h',
      'Billable h',
      'Non-billable h',
      'Entries',
    ]);
    expect(table.body[0]).toEqual([
      'Casey Contributor',
      'ALPHA · Alpha Platform',
      'March 2026',
      '31.75',
      '20.5',
      '11.25',
      '7',
    ]);
    expect(table.foot).toEqual(['Total', '', '', '31.75', '20.5', '11.25', '7']);
    expect(table.numericColumns).toEqual([3, 4, 5, 6]);
  });

  it('has only the grouped columns plus the numbers', () => {
    const byMonth: HoursReport = {
      ...report,
      groupBy: ['month'],
      totals: { totalHours: 1, billableHours: 1, nonBillableHours: 0, entryCount: 1 },
      rows: [
        { month: '2026-03', totalHours: 1, billableHours: 1, nonBillableHours: 0, entryCount: 1 },
      ],
    };

    const table = buildPdfTable(byMonth);

    expect(table.head).toEqual(['Month', 'Total h', 'Billable h', 'Non-billable h', 'Entries']);
    expect(table.foot).toEqual(['Total', '1', '1', '0', '1']);
    expect(table.numericColumns).toEqual([1, 2, 3, 4]);
  });

  it('names the file after the period', () => {
    expect(hoursReportFileName(report)).toBe('hours-report_2026-02-01_to_2026-03-31.pdf');
  });
});

describe('PDF document', () => {
  it('is a real PDF holding the title, filters, rows and totals', async () => {
    const bytes = await pdfText(report, { ...meta, filters: ['Project: ALPHA · Alpha Platform'] });
    const text = asText(bytes);

    expect(text.startsWith('%PDF-')).toBe(true);
    for (const expected of [
      'Hours report',
      'Period: 2026-02-01 to 2026-03-31',
      'Generated by Alex Admin on 2026-03-31',
      'Project: ALPHA',
      'Casey Contributor',
      'March 2026',
      '31.75',
      'Total',
    ]) {
      expect(text, expected).toContain(expected);
    }
  });

  it('says so when the report was cut at 5000 rows', async () => {
    const text = asText(await pdfText({ ...report, truncated: true }));

    expect(text).toContain('first 5000 rows');
  });

  it('breaks long reports over several pages', async () => {
    const many: HoursReport = {
      ...report,
      rows: Array.from({ length: 120 }, (_, i) => ({
        ...report.rows[0]!,
        userName: `Person ${i}`,
      })),
    };

    const doc = await buildHoursReportPdf(many, meta);

    expect(doc.getNumberOfPages()).toBeGreaterThan(1);
  });
});

describe('Download PDF button', () => {
  const today = todayIso();
  const backend = (reportBody: HoursReport | Response) =>
    mockApi({
      ...signedInAs(users.contributor),
      'GET /projects': ok({ projects: [project()] }),
      'GET /reports/hours': reportBody instanceof Response ? reportBody : ok(reportBody),
    });
  const open = async () => {
    renderRoutes('/reports');
    await screen.findByRole('heading', { name: 'Hours report' });
  };
  const monthReport: HoursReport = { ...report, groupBy: ['month'], from: today, to: today };

  /** Stubs the browser download: records the file name and the Blob that would be saved. */
  const captureDownload = () => {
    const saved: { name: string; blob: Blob }[] = [];
    let current: Blob | undefined;
    vi.stubGlobal(
      'URL',
      Object.assign(URL, {
        createObjectURL: vi.fn((blob: Blob) => ((current = blob), 'blob:test')),
        revokeObjectURL: vi.fn(),
      }),
    );
    vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(function (
      this: HTMLAnchorElement,
    ) {
      saved.push({ name: this.download, blob: current! });
    });
    return saved;
  };

  it('saves exactly this report as a PDF named after the period', async () => {
    const saved = captureDownload();
    backend(monthReport);
    await open();

    await userEvent.click(await screen.findByRole('button', { name: 'Download PDF' }));

    await waitFor(() => expect(saved).toHaveLength(1));
    expect(saved[0]!.name).toBe(`hours-report_${today}_to_${today}.pdf`);
    expect(saved[0]!.blob.type).toBe('application/pdf');
    expect(asText(await saved[0]!.blob.arrayBuffer()).startsWith('%PDF-')).toBe(true);
  });

  it('is not offered when there is nothing to export', async () => {
    backend({ ...monthReport, rows: [] });
    await open();

    expect(await screen.findByText('No hours in this range')).toBeInTheDocument();
    expect(screen.queryByRole('button', { name: 'Download PDF' })).not.toBeInTheDocument();
  });

  it('is not offered while the report failed to load', async () => {
    backend(fail(500, 'INTERNAL_ERROR', 'An unexpected error occurred'));
    await open();

    expect(await screen.findByText('Could not run the report')).toBeInTheDocument();
    expect(screen.queryByRole('button', { name: 'Download PDF' })).not.toBeInTheDocument();
  });

  it('shows a message instead of crashing when the PDF cannot be created', async () => {
    vi.stubGlobal(
      'URL',
      Object.assign(URL, {
        createObjectURL: () => {
          throw new Error('boom');
        },
      }),
    );
    backend(monthReport);
    await open();

    await userEvent.click(await screen.findByRole('button', { name: 'Download PDF' }));

    const alert = await screen.findByRole('alert');
    expect(alert).toHaveTextContent('Could not create the PDF');
    expect(within(alert).queryByText(/boom/)).not.toBeInTheDocument(); // no raw exception text
    expect(screen.getByRole('button', { name: 'Download PDF' })).toBeEnabled();
  });
});
